const catalogs: Record<Locale, Record<MsgKey, string>> = {
  "pt-BR": ptBR,
  "en-US": enUS,
};

let current: Locale = "pt-BR";

export function getLocale(): Locale {
  return current;
}

export function setLocale(locale: Locale): void {
  current = locale;
}

export function t(key: MsgKey, vars?: Record<string, string | number>): string {
  let s = catalogs[current][key] ?? catalogs["pt-BR"][key] ?? key;
  if (vars) {
    for (const [k, v] of Object.entries(vars)) {
      s = s.replaceAll(`{${k}}`, String(v));
    }
  }
  return s;
}

export function isScriptNotice(line: string): boolean {
  return (
    line.includes("Script de testes criados") ||
    line.includes("Script de testes encontrados") ||
    line.includes("Test scripts created") ||
    line.includes("Test scripts found")
  );
}
