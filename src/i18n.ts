export type Locale = "pt-BR" | "en-US";

export function parseLocale(raw: unknown): Locale | undefined {
  const v = String(raw ?? "")
    .trim()
    .toLowerCase()
    .replace("_", "-");
  if (v === "pt-br" || v === "pt" || v === "pt-brz") return "pt-BR";
  if (v === "en-us" || v === "en" || v === "en-usa") return "en-US";
  return undefined;
}

